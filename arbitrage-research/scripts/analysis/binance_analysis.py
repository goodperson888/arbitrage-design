def analyze_klines(klines):
    """分析 K 线数据"""
    analysis = []
    
    for kline in klines:
        open_time = kline[0]
        open_price = float(kline[1])
        high_price = float(kline[2])
        low_price = float(kline[3])
        close_price = float(kline[4])
        
        # 计算涨跌
        change = close_price - open_price
        change_pct = (change / open_price) * 100 if open_price > 0 else 0
        direction = "UP" if change > 0 else "DOWN"
        
        # 简单技术指标
        body_size = abs(close_price - open_price)
        upper_shadow = high_price - max(open_price, close_price)
        lower_shadow = min(open_price, close_price) - low_price
        
        analysis.append({
            'open_time': open_time,
            'open': open_price,
            'high': high_price,
            'low': low_price,
            'close': close_price,
            'change': change,
            'change_pct': change_pct,
            'direction': direction,
            'body_size': body_size,
            'upper_shadow': upper_shadow,
            'lower_shadow': lower_shadow
        })
    
    return analysis

def calculate_indicators(analysis):
    """计算技术指标"""
    if len(analysis) < 5:
        return None
    
    closes = [k['close'] for k in analysis]
    
    # 移动平均
    sma_5 = sum(closes[-5:]) / 5
    sma_10 = sum(closes[-10:]) / 10 if len(closes) >= 10 else sma_5
    
    # 动量
    momentum = closes[-1] - closes[-5]
    
    # 简单预测信号
    # 如果收盘价高于 5 日均线，预测上涨；否则预测下跌
    if closes[-1] > sma_5:
        prediction = "UP"
    else:
        prediction = "DOWN"
    
    return {
        'sma_5': sma_5,
        'sma_10': sma_10,
        'momentum': momentum,
        'current_price': closes[-1],
        'prediction': prediction
    }

def main():
    print("=== 币安 BTC 5 分钟 K 线分析 ===\n")
    
    # 分析 K 线
    analysis = analyze_klines(binance_klines)
    
    print(f"分析了 {len(analysis)} 根 5 分钟 K 线\n")
    
    # 显示最近 10 根 K 线
    print("=== 最近 10 根 K 线 ===")
    for k in analysis[-10:]:
        direction_emoji = "📈" if k['direction'] == "UP" else "📉"
        print(f"{direction_emoji} {datetime.fromtimestamp(k['open_time']/1000).strftime('%H:%M')} 开:{k['open']:.2f} 收:{k['close']:.2f} ({k['change_pct']:+.2f}%)")
    
    # 计算指标
    indicators = calculate_indicators(analysis)
    
    if indicators:
        print(f"\n=== 技术指标 ===")
        print(f"当前价格: ${indicators['current_price']:.2f}")
        print(f"SMA 5: ${indicators['sma_5']:.2f}")
        print(f"SMA 10: ${indicators['sma_10']:.2f}")
        print(f"动量: ${indicators['momentum']:.2f}")
        print(f"\n=== 简单预测策略 ===")
        print(f"基于 5 日均线预测下一个 5 分钟: {indicators['prediction']}")
    
    # 统计涨跌分布
    up_count = sum(1 for k in analysis if k['direction'] == 'UP')
    down_count = sum(1 for k in analysis if k['direction'] == 'DOWN')
    
    print(f"\n=== 历史涨跌分布 ===")
    print(f"上涨: {up_count} 次 ({up_count/len(analysis)*100:.1f}%)")
    print(f"下跌: {down_count} 次 ({down_count/len(analysis)*100:.1f}%)")
    
    # 保存数据
    with open(DATA_DIR / "binance_analysis.json", 'w') as f:
        json.dump({
            'analysis': analysis,
            'indicators': indicators,
            'statistics': {
                'up_count': up_count,
                'down_count': down_count,
                'total': len(analysis)
            }
        }, f, indent=2)
    
    print(f"\n✓ 数据已保存到: {DATA_DIR / 'binance_analysis.json'}")

if __name__ == "__main__":
    main()